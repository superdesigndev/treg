EXAMPLE = {("facebook-post", "post"): "https://www.facebook.com/NASA/posts/1110592997763013"}
TYPES = {"string": "string", "integer": "integer", "int": "integer", "number": "number", "float": "number",
         "boolean": "boolean", "bool": "boolean", "list": "array[string]",
         "array": "array[string]", "object": "object"}
_EMAIL = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_PHONE = re.compile(r"\+\d[\d ()-]{7,}\d")
# In a comment or review sample the people who wrote them are private individuals: their names,
# handles and profile links are blanked. The page or account the recipe was asked about stays.
_PERSON = re.compile(r"(author|user|reviewer|commenter|owner|handle|avatar|profile|name)", re.I)
_PEOPLE_JOBS = ("comments", "reviews", "replies")


def _block(text: str, section: str, indent: str, body: str, at_end: bool = False) -> str:
    """Replace the marked recipes block inside `section` (or add it): right after the section
    header, or at the end of the file for the endpoint list."""
    block = f"{indent}{BEGIN}\n" + "".join(f"{indent}{line}\n" if line else "\n" for line in body.rstrip().split("\n")) + f"{indent}{END}\n"
    start, stop = text.find(f"{indent}{BEGIN}\n", text.index(section)), None
    if start != -1:
        stop = text.index(f"{indent}{END}\n", start) + len(f"{indent}{END}\n")
        return text[:start] + block + text[stop:]
    if at_end:
        return text.rstrip("\n") + "\n\n" + block
    at = text.index(section) + len(section)
    return text[:at] + block + text[at:]


def _name(title: str) -> str:
    """The catalog caps a tool name at 60 characters; cut at a word."""
    return title if len(title) <= 60 else title[:57].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def recipes(path: str | None) -> list[dict]:
    if path:
        doc = json.loads(Path(path).read_text())
    else:
        key = os.environ["TREG_CATALOG_CRED"]
        doc = httpx.get(f"{BASE}/recipes", headers={"Authorization": f"Bearer {key}"}, timeout=60).json()
    return list(doc["recipes"] if isinstance(doc, dict) else doc)


def _short(value, depth=0, people=False):
    """An example cut to what a reader needs: two rows, short strings, no contact details, and in
    a comment or review sample no names of the people who wrote them."""
    if isinstance(value, dict):
        return {k: ("[redacted]" if people and v and _PERSON.search(k) and not isinstance(v, (int, float, bool))
                    else _short(v, depth + 1, people)) for k, v in value.items()}
    if isinstance(value, list):
        return [_short(v, depth + 1, people) for v in value[:2]]
    if isinstance(value, str):
        value = _PHONE.sub("[phone]", _EMAIL.sub("[email]", value))
        return value if len(value) <= 300 else value[:300] + "…"
    return value


def endpoint(r: dict, cap: str, today: str, captured: dict | None) -> dict:
    inputs = {k: v for k, v in (r.get("inputs") or {}).items() if not v.get("secret")}
    body = {}
    for name, spec in inputs.items():
        field = {"type": TYPES.get(str(spec.get("type")), "string"), "required": bool(spec.get("required"))}
        note = spec.get("about") or spec.get("description") or spec.get("note")
        if spec.get("default") is not None:
            note = f"{note + '; ' if note else ''}default {spec['default']}"
        if note:
            field["note"] = str(note)
        spec = {**spec, "example": EXAMPLE.get((r["name"], name), spec.get("example"))}
        inputs[name] = spec
        if spec.get("example") is not None:
            field["example"] = spec["example"]
        body[name] = field
    columns = ", ".join(r.get("output") or [])
    summary = " ".join(str(r.get("description") or r.get("title") or "").split())
    if columns:
        summary += f" Columns: {columns}."
    ep: dict = {
        "id": f"crawl4ai.{cap}",
        "async": False,
        "capability": cap,
        "platform": cap.split(".")[0],
        "scope": "any_account",
        "method": "POST",
        "path": f"/recipes/{r['name']}",
        "name": _name(str(r.get("title") or r["name"])),
        "summary": summary,
        "body_allowlist": True,
        "input": {"bodyType": "json", "body": body},
        "cost": {
            "type": "per_success", "value": PRICE.get(r["name"], DEFAULT_PRICE), "currency": "credit",
            "per": 1, "unit": "call",
            "source": "observed", "source_url": f"{BASE}/recipes", "checked": today,
            "confidence": "verified",
            "note": (f"treg's account price: {PRICE.get(r['name'], DEFAULT_PRICE):g} credits a call whatever pages the run fetched, "
                     "second-source records included; a reply with no rows, a refused input and "
                     "a failed run are free. The x-c4-cost header settles the actual charge."),
        },
        "docs_url": "https://crawl4ai.com/llms.txt",
    }
    test = {k: v["example"] for k, v in inputs.items() if v.get("required") and v.get("example") is not None}
    if not test:
        # A recipe whose inputs are alternatives (a username OR a numeric id) marks none required;
        # it is tested with the first one that carries an example.
        alt = [k for k, v in inputs.items()
               if v.get("example") not in (None, False, "") and k not in ("limit", "sort", "country", "language")]
        if alt:
            test = {alt[0]: inputs[alt[0]]["example"]}
    if all(v.get("example") is not None for v in inputs.values() if v.get("required")):
        ep["test_request"] = {"body": test}     # a recipe with no required input runs on {}
    if captured and captured.get("ok"):
        ep["verified"] = captured.get("verified", today)
        ep["example_response"] = f"examples/{ep['id']}.json"
    elif "test_request" in ep:
        ep["unverified"] = (captured or {}).get("why") or "not run yet"
    else:
        ep["untestable"] = "the recipe lists no example for a required input"
    return ep


def capture(r: dict, test: dict | None, key: str, people: bool = False) -> dict:
    if test is None:
        return {"ok": False, "why": "no example inputs"}
    try:
        resp = httpx.post(f"{BASE}/recipes/{r['name']}", json=test["body"],
                          headers={"Authorization": f"Bearer {key}"}, timeout=300)
        doc = resp.json()
    except Exception as exc:  # noqa: BLE001 - a capture failure leaves the row unverified
        return {"ok": False, "why": f"capture failed: {type(exc).__name__}"}
    rows = doc.get("rows") if isinstance(doc, dict) else None
    if resp.status_code != 200 or not rows:
        return {"ok": False, "why": f"capture answered {resp.status_code} with {len(rows or [])} rows"}
    out = _short({k: v for k, v in doc.items() if k != "rows"})
    out["rows"] = _short(rows, 1, people)
    return {"ok": True, "doc": out, "cost": resp.headers.get("x-c4-cost")}


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="src")
    ap.add_argument("--capture", action="store_true")
    args = ap.parse_args(argv)
    today = dt.date.today().isoformat()
    taxonomy = yaml.safe_load((CATALOG / "capabilities.yaml").read_text())
    known, platforms = set(taxonomy["capabilities"]), set(taxonomy.get("platforms") or {})
    proposed: dict[str, str] = {}
    endpoints: list[dict] = []
    verified = dict(re.findall(r"- id: (crawl4ai\.\S+)\n(?:    .*\n)*?    verified: '([\d-]+)'", OUT.read_text()))
    seen: set[str] = set()
    for r in sorted(recipes(args.src), key=lambda r: CAPABILITY.get(r["name"], "~")):
        if r.get("run") == "job":
            continue
        cap = CAPABILITY.get(r["name"])
        if cap is None:
            print(f"skip {r['name']}: no capability mapped; add it to CAPABILITY", file=sys.stderr)
            continue
        if cap.split(".")[0] not in platforms:
            raise SystemExit(f"{r['name']}: platform {cap.split('.')[0]!r} is not in capabilities.yaml platforms")
        if cap in seen:
            raise SystemExit(f"{r['name']}: capability {cap} already taken by another recipe")
        seen.add(cap)
        if cap not in known:
            proposed[cap] = str(r.get("title") or r["name"])
        draft = endpoint(r, cap, today, None)
        captured = None
        if not args.capture and (EXAMPLES / f"{draft['id']}.json").exists() and draft["id"] in verified:
            captured = {"ok": True, "verified": verified[draft["id"]]}
        if args.capture:
            captured = capture(r, draft.get("test_request"), os.environ["TREG_CATALOG_CRED"],
                               people=cap.rsplit(".", 1)[-1] in _PEOPLE_JOBS)
            if captured.get("ok"):
                (EXAMPLES / f"{draft['id']}.json").write_text(json.dumps(captured["doc"], indent=2, ensure_ascii=False) + "\n")
            print(f"{r['name']:28} {'ok ' + str(captured.get('cost')) if captured.get('ok') else captured.get('why')}")
        endpoints.append(endpoint(r, cap, today, captured))
    text = OUT.read_text()
    added = dict(re.findall(r"- id: (crawl4ai\.\S+)\n(?:    .*\n)*?    added: '([\d-]+)'", text))
    for ep in endpoints:
        if ep["id"] in added:
            ep["added"] = added[ep["id"]]
    caps = yaml.safe_dump(dict(sorted(proposed.items())), sort_keys=False, allow_unicode=True, width=110)
    eps = yaml.safe_dump(endpoints, sort_keys=False, allow_unicode=True, width=110)
    text = _block(text, "proposed_capabilities:\n", "  ", caps)
    text = _block(text, "endpoints:\n", "  ", eps, at_end=True)
    OUT.write_text(text)
    print(f"wrote {len(endpoints)} recipes, {len(proposed)} proposed capabilities -> {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
