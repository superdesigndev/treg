"""Write the recipes block of `src/treg/catalog/crawl4ai.yaml` from Crawl4AI's live recipe list.

A Crawl4AI recipe is one ready-made scraper for one site and one job (`POST /recipes/{name}`,
rows back in fixed columns). This script turns `GET /recipes` into catalog rows, one tool per
recipe, each filed under the treg capability it answers, so catalog search finds it by job and
comparison sets it beside the other providers of that job. Re-run it when the recipe list changes:
it rewrites only the two marked blocks (proposed capabilities, endpoints) and keeps each tool's
`added:` day.

    TREG_CATALOG_CRED=<crawl4ai key> uv run --frozen python scripts/catalog_ingest_crawl4ai_recipes.py
    ... --capture   also run every recipe once with its own example inputs and save the answer as
                    the endpoint's example (its own price per call; a failed call is free)
    ... --from FILE read the recipe list from a saved `GET /recipes` answer instead of the API

Recipes that only run as jobs (`run: job`) are left out: the catalog row is a single call. A
recipe input marked `secret` (a caller's own login cookies) is never declared, and
`body_allowlist` keeps any undeclared field from being relayed.

A row's summary, note and parameter notes come from TEXT, written to the catalog's rules for them
(docs/context/architecture/catalog-schema.md, "Summary and note") from the recipe's description.
A recipe TEXT does not name yet gets its description's first sentence, and the run says so.
"""
