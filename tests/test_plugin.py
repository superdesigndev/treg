def test_the_dsh_bundle_declares_the_patch_dsh_reads():
    """dsh does not read a `plugin.json`. It installs a package whose `package.json` declares
    `dsh.bundle.patch`, and a package without that declaration installs as a plain dependency that
    activates NO layer — `dsh plugin` prints a warning and the user gets nothing, silently enough to
    look like it worked."""
    manifest = json.loads(DSH_MANIFEST.read_text(encoding="utf-8"))
    assert manifest["dsh"]["bundle"]["patch"] == "./dsh/cordis.patch.yml"
    assert (ROOT / manifest["dsh"]["bundle"]["patch"][2:]).exists()
    assert manifest["type"] == "module", "the entry is plain ESM; CommonJS would fail to load it"
    assert (ROOT / manifest["main"]).exists(), f"`main` points at {manifest['main']}, which is missing"
    for rel in manifest["files"]:
        assert (ROOT / rel).exists(), f"`files` ships {rel}, which does not exist"


def test_the_dsh_bundle_needs_no_build_step():
    """`dsh plugin add github:...` fetches SOURCES, not build output. A package with a `prepare`
    script makes pnpm refuse the install until the user allowlists the build in their profile's
    pnpm-workspace.yaml — i.e. the documented install command fails for everyone on first run. The
    entry is therefore hand-written ESM, and depends on nothing."""
    manifest = json.loads(DSH_MANIFEST.read_text(encoding="utf-8"))
    assert "prepare" not in manifest.get("scripts", {})
    assert not manifest.get("dependencies"), (
        "an out-of-tree bundle that depends on an in-box @deepseek-ai package installs a SECOND "
        "copy of it, which then drifts from the host's")


def test_the_dsh_mcp_row_is_disabled_until_there_is_a_token():
    """dsh's MCP row is header-authed, so registered before anyone has a token it is five
    always-on tools that 401 on every call. The row exists but is disabled until `TREG_TOKEN` is in
    the environment, so a token-holder gets the tools at boot and everyone else a clean install."""
    patch = DSH_PATCH.read_text(encoding="utf-8")
    assert "@deepseek-ai/dsh-mcp-client" in patch
    assert "disabled: !!js (process.env.TREG_TOKEN ?? '') === ''" in patch, (
        "the MCP row must stay disabled until TREG_TOKEN exists")
    # Found by running the real dsh against this file: an expression that STARTS with `!` makes the
    # YAML parser read a second tag property, and the whole profile fails to load with
    # "duplication of a tag property" — not just this row. So `!process.env.TREG_TOKEN` is banned.
    assert "!!js !" not in patch, "a `!!js` expression must not begin with `!`"
    assert "https://treg.to/mcp/" in patch
    assert "localhost" not in patch and "127.0.0.1" not in patch


