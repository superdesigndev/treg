def test_the_bare_skill_carries_the_version_clawhub_requires():
    """ClawHub refuses a skill whose frontmatter lacks a semver `version`, and requires `name` to
    match the parent directory."""
    fm = frontmatter(BARE_SKILL)
    assert fm["name"] == "treg" == BARE_SKILL.parent.name
    assert fm["version"] == package_version()
    assert fm.get("description"), "the description is what drives discovery in every registry"


def test_the_claude_marketplace_installs_the_plugin_folder():
    """A marketplace `source` of the repo root ships the whole repository and every workflow skill
    under `skills/`. It must name the one plugin folder Cursor also installs."""
    market = json.loads(CLAUDE_MARKETPLACE.read_text(encoding="utf-8"))
    manifest = json.loads(CLAUDE_MANIFEST.read_text(encoding="utf-8"))
    entry = market["plugins"][0]
    assert entry["name"] == manifest["name"] == "treg"
    assert (ROOT / entry["source"]).resolve() == PLUGIN_DIR.resolve()
    assert [p.parent.name for p in (PLUGIN_DIR / "skills").glob("*/SKILL.md")] == ["treg"]
    assert not (ROOT / ".claude-plugin" / "plugin.json").exists(), (
        "a root manifest would make the repository root a second plugin")


def test_every_workflow_skill_is_its_own_optional_plugin():
    """The workflow skills ride beside `treg`, one plugin each, so `/plugin` offers them one by one
    rather than installing all of them with treg."""
    market = json.loads(CLAUDE_MARKETPLACE.read_text(encoding="utf-8"))
    workflows = sorted(p.parent.name for p in (ROOT / "src/treg/web/skills").glob("*/SKILL.md"))
    entries = market["plugins"][1:]
    assert [e["name"] for e in entries] == workflows
    for entry in entries:
        root = (ROOT / entry["source"]).resolve()
        assert [p.parent.name for p in (root / "skills").glob("*/SKILL.md")] == [entry["name"]]
        plugin = json.loads((root / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
        assert plugin["name"] == entry["name"] and plugin["version"] == package_version()


def test_the_claude_plugin_declares_a_typed_oauth_mcp_server():
    """Claude Code rejects a server with a `url` and no `type` (it logs the error and registers
    nothing), which is why this is not the `url`-only `mcp.json` Cursor and Grok Bot read. No
    header: the host runs OAuth, and the server waits as "needs authentication" until sign-in."""
    manifest = json.loads(CLAUDE_MANIFEST.read_text(encoding="utf-8"))
    assert manifest["mcpServers"] == {"treg": {"type": "http", "url": "https://treg.to/mcp/"}}
    cursor = json.loads((PLUGIN_DIR / "mcp.json").read_text(encoding="utf-8"))
    assert cursor["mcpServers"]["treg"]["url"] == manifest["mcpServers"]["treg"]["url"]


def test_the_codex_marketplace_installs_the_codex_plugin():
    """Codex reads `.agents/plugins/marketplace.json` and falls back to the Claude marketplace,
    which would hand it the Cursor/Claude folder instead of the reviewed Codex plugin."""
    market = json.loads(CODEX_MARKETPLACE.read_text(encoding="utf-8"))
    (entry,) = market["plugins"]
    assert entry["name"] == "treg"
    assert entry["source"] == {"source": "local", "path": "./plugin"}
    assert (ROOT / entry["source"]["path"]).resolve() == PLUGIN.resolve()
    assert entry["policy"] == {"installation": "AVAILABLE", "authentication": "ON_INSTALL"}


def test_the_codex_subtitle_fits_the_field():
    """Codex renders `shortDescription` as the listing SUBTITLE, and the upload form rejects
    anything over 30 characters — so it cannot carry the full positioning sentence the way the
    Claude manifest's `description` does. It keeps the front half, which is the half that
    identifies the product."""
    subtitle = json.loads(MANIFEST.read_text(encoding="utf-8"))["interface"]["shortDescription"]
    assert len(subtitle) <= 30, f"subtitle is {len(subtitle)} chars, the field allows 30"
    assert subtitle.split()[0] in POSITIONING


def test_the_cursor_layout_matches_cursors_template():
    """Cursor prescribes the shape (github.com/cursor/plugin-template): marketplace manifest at the
    repo root, plugin under plugins/<name>/ with its own .cursor-plugin/plugin.json, and `source`
    the relative path to that folder. Unlike Claude Code, the plugin root is never the repo root —
    get that wrong and the listing installs nothing. Their own validator agrees with this test."""
    market = json.loads(CURSOR_MARKETPLACE.read_text(encoding="utf-8"))
    manifest = json.loads(CURSOR_MANIFEST.read_text(encoding="utf-8"))

    assert len(market["plugins"]) == 1
    entry = market["plugins"][0]
    assert entry["name"] == manifest["name"] == "treg"
    assert entry["name"] == entry["name"].lower() and " " not in entry["name"]  # kebab-case
    assert entry["source"] == f"./plugins/{entry['name']}", (
        "`source` must be the relative path to the plugin folder, and match the folder name")

    root = (ROOT / entry["source"]).resolve()
    assert root == PLUGIN_DIR.resolve()
    assert (root / ".cursor-plugin" / "plugin.json").exists()
    assert (root / "skills" / "treg" / "SKILL.md").exists()

    # Cursor's marketplace schema differs from Claude's: a metadata{} block rather than a top-level
    # description, and no $schema. Do not "fix" one to look like the other.
    assert market["metadata"]["description"] and market["metadata"]["version"]
    assert "description" not in market

    logo = manifest["logo"]
    assert not logo.startswith("./"), "the template writes `assets/logo.svg`, not `./assets/...`"
    assert (root / logo).exists(), f"plugin.json points at {logo}, which does not exist"


def test_the_cursor_plugin_ships_mcp_alongside_the_skill():
    """Cursor now ships MCP tools alongside the skill, so users don't need `treg mcp install`.
    The manifest declares `mcpServers` pointing at a config file, and that file declares the URL
    only: the host runs OAuth. A `${env:TREG_TOKEN}` header made Grok Bot, which installs this
    plugin, ask for the variable before sign-in and fail on phones where it cannot be set."""
    manifest = json.loads(CURSOR_MANIFEST.read_text(encoding="utf-8"))
    assert manifest["mcpServers"] == "./mcp.json", "the manifest must point to the MCP config"
    assert manifest["skills"] == "./skills/", "the manifest must still ship the skill"

    mcp_config = json.loads((PLUGIN_DIR / "mcp.json").read_text(encoding="utf-8"))
    assert "mcpServers" in mcp_config, "Cursor's MCP config uses the { mcpServers: {...} } wrapper"
    assert "treg" in mcp_config["mcpServers"]
    server = mcp_config["mcpServers"]["treg"]
    assert server["url"] == "https://treg.to/mcp/", "the MCP URL must be the production endpoint"
    assert set(server) == {"url"}, "url only: a token header blocks the host's own OAuth sign-in"
    assert "localhost" not in server["url"] and "127.0.0.1" not in server["url"]


