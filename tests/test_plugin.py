"""The plugins — shop windows whose contents must not drift from the product, or from each other.

Five of them now, generated by `scripts/build_plugin.py` from the one source `src/treg/web/skill.md`:

- **Codex/ChatGPT** (`plugin/`) — declares an MCP connector, so its skill checks for the MCP tools
  first and falls back to the CLI (the directory's upload path strips connector config).
- **Claude Code and Cursor** (root `.claude-plugin/` and `.cursor-plugin/` marketplaces, one plugin
  folder `plugins/treg/`): declare the remote MCP server, so the skill checks for the tools first
  like Codex. The bare skill `skills/treg/` at the repo root is what `npx skills add` and ClawHub
  publish, written around the CLI.
- **DeepSeek Harness** (root `package.json` + `dsh/`) — no manifest at all: an npm package declaring
  `dsh.bundle`, whose patch mounts the skill and a treg MCP row that is disabled until there is a
  token. See docs/DSH-PLUGIN.md.
- **MiniMax** (`plugins/minimax/`): skills-only, because MiniMax admits an authenticated MCP only
  through its App/Connector program. The served page unchanged. See docs/MINIMAX-PLUGIN.md.

A generated file that nobody checks is a copy, and a copy rots — so the first test here is the one
that matters: regenerate, and fail if any checked-in copy differs.

The rest guard the manifests, because they are read by public directories rather than by us. A
broken path, an unsubstituted placeholder, or two listings that describe the product differently is
invisible locally and embarrassing in a store.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugin"
MANIFEST = PLUGIN / ".codex-plugin" / "plugin.json"
SKILL = PLUGIN / "skills" / "treg" / "SKILL.md"

CLAUDE_MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"
CODEX_MARKETPLACE = ROOT / ".agents" / "plugins" / "marketplace.json"
BARE_SKILL = ROOT / "skills" / "treg" / "SKILL.md"

# Cursor prescribes its own layout (github.com/cursor/plugin-template): marketplace manifest at the
# repo root, each plugin under plugins/<name>/ with its own .cursor-plugin/plugin.json. The plugin
# root is NEVER the repo root here — that is the difference from Claude Code that is easy to get
# wrong, and `source` pointing at the wrong place installs an empty plugin.
CURSOR_MARKETPLACE = ROOT / ".cursor-plugin" / "marketplace.json"
PLUGIN_DIR = ROOT / "plugins" / "treg"
CURSOR_MANIFEST = PLUGIN_DIR / ".cursor-plugin" / "plugin.json"
PLUGIN_SKILL = PLUGIN_DIR / "skills" / "treg" / "SKILL.md"
CLAUDE_MANIFEST = PLUGIN_DIR / ".claude-plugin" / "plugin.json"

# DeepSeek Harness has no plugin manifest at all: it installs an npm package whose `package.json`
# declares `dsh.bundle`, pointing at a config layer. So the "manifest" here is package.json, and the
# thing that decides what a user gets is the patch — hence the extra tests at the bottom.
DSH_MANIFEST = ROOT / "package.json"
DSH_PATCH = ROOT / "dsh" / "cordis.patch.yml"
DSH_ENTRY = ROOT / "dsh" / "index.js"
DSH_SKILL = ROOT / "dsh" / "skills" / "treg" / "SKILL.md"

# MiniMax (MiniMax Code + MiniMax Agent) prescribes `.minimax-plugin/plugin.json` at the plugin root
# and rejects any package holding a credential, so this one is skills-only from its own root
# `plugins/minimax/`, submitted as a GitHub subdirectory or a wrapper-free ZIP. See docs/MINIMAX-PLUGIN.md.
MINIMAX_PLUGIN_DIR = ROOT / "plugins" / "minimax"
MINIMAX_MANIFEST = MINIMAX_PLUGIN_DIR / ".minimax-plugin" / "plugin.json"
MINIMAX_SKILL = MINIMAX_PLUGIN_DIR / "skills" / "treg" / "SKILL.md"

# Every generated SKILL.md, and every manifest a public directory reads. Tests that apply to the
# product as a whole (version, positioning, no-routing) parametrise over these rather than being
# written against whichever plugin happened to exist first.
ALL_SKILLS = {"codex": SKILL, "skills": BARE_SKILL, "plugin": PLUGIN_SKILL, "dsh": DSH_SKILL,
              "minimax": MINIMAX_SKILL}
ALL_MANIFESTS = {"codex": MANIFEST, "claude": CLAUDE_MANIFEST, "cursor": CURSOR_MANIFEST,
                 "dsh": DSH_MANIFEST, "minimax": MINIMAX_MANIFEST}

# The one line that positions the product. It is the same sentence `llms.txt` opens with, and it is
# hand-maintained in three places across two stores — which is exactly the shape of thing that
# drifts, so it is pinned rather than trusted.
POSITIONING = "Live data for AI agents"


def package_version() -> str:
    pyproject = (ROOT / "pyproject.toml").read_text(encoding="utf-8")
    return next(l.split('"')[1] for l in pyproject.splitlines() if l.startswith("version = "))


def frontmatter(path: Path) -> dict:
    """The skill's YAML frontmatter as a flat dict. Deliberately a 6-line parser and not a yaml
    import: the CLI-path modules must not gain a heavy dependency, and the frontmatter here is
    three scalar keys."""
    text = path.read_text(encoding="utf-8")
    assert text.startswith("---\n"), f"{path} does not open with frontmatter"
    block = text.split("---", 2)[1]
    out = {}
    for line in block.strip().splitlines():
        key, _, value = line.partition(":")
        out[key.strip()] = value.strip()
    return out


@pytest.fixture(scope="module")
def manifest() -> dict:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def test_the_plugin_skill_is_not_stale():
    """`build_plugin.py --check` is the whole point: the served skill.md is the ONE source, and this
    is what notices when the plugin falls behind it."""
    r = subprocess.run([sys.executable, str(ROOT / "scripts" / "build_plugin.py"), "--check"],
                       capture_output=True, text=True)
    assert r.returncode == 0, (
        f"plugin SKILL.md is stale — regenerate with `uv run python scripts/build_plugin.py`\n"
        f"{r.stdout}{r.stderr}")


@pytest.mark.parametrize("variant", sorted(ALL_SKILLS))
def test_no_unsubstituted_placeholder_reaches_the_plugin(variant):
    """`{BASE}` is substituted per-request by the SERVER. Nothing substitutes it inside an installed
    plugin, so shipping the literal would break every URL in the most-read page of the product."""
    text = ALL_SKILLS[variant].read_text(encoding="utf-8")
    assert "{BASE}" not in text
    # The Codex skill rides an MCP connector and must not install anything (OpenAI's plugin review
    # refuses a skill that downloads or runs code outside the package); every other copy installs the CLI.
    assert ("https://treg.to/install.sh" in text) is (variant != "codex")


def test_the_connector_points_at_production_over_https():
    """The listing is public. A plugin shipped pointing at a dev box or over http would work for
    exactly one person, and reviewers test from their own machines."""
    import json as _json
    mcp = _json.loads((PLUGIN / ".mcp.json").read_text(encoding="utf-8"))
    # The documented shape (`mcpServers`, url only): the OpenAI plugin portal offers no Connect for a
    # server declared any other way. Auth is OAuth, which the portal and Codex both run themselves.
    assert set(mcp) == {"mcpServers"} and set(mcp["mcpServers"]) == {"treg"}
    url = mcp["mcpServers"]["treg"]["url"]
    assert url.startswith("https://"), url
    assert "ngrok" not in url and "localhost" not in url and "127.0.0.1" not in url


def test_at_most_three_default_prompts(manifest):
    """OpenAI's upload form rejects the bundle outright: "`interface.defaultPrompt` must contain at
    most three prompts." Nothing local surfaced that — it cost an upload round-trip to find, which is
    exactly the kind of limit worth pinning rather than rediscovering."""
    prompts = manifest["interface"]["defaultPrompt"]
    assert 1 <= len(prompts) <= 3, f"the directory allows at most 3 default prompts, found {len(prompts)}"


def test_every_declared_path_exists(manifest):
    """A path that resolves on the author's machine and nowhere else is the classic packaging bug."""
    paths = [manifest["skills"], manifest["interface"]["composerIcon"], manifest["interface"]["logo"]]
    paths += manifest["interface"].get("screenshots", [])
    for rel in paths:
        assert rel.startswith("./"), f"{rel} must be relative to the plugin root"
        assert (PLUGIN / rel[2:]).exists(), f"plugin.json points at {rel}, which does not exist"


@pytest.mark.parametrize("variant", sorted(ALL_MANIFESTS))
def test_plugin_version_tracks_the_package(variant):
    """One product, one version. A listing that claims 0.1.0 while the CLI is 0.7.0 is a support
    question waiting to happen."""
    manifest = json.loads(ALL_MANIFESTS[variant].read_text(encoding="utf-8"))
    assert manifest["version"] == package_version()


